function plan(
  points: readonly (readonly [x: number, y: number])[],
): readonly PlanPoint[] {
  return Object.freeze(
    points.map(([x, y]) => Object.freeze({ x, y })),
  );
}

function rectangle(
  centerX: number,
  centerY: number,
  width: number,
  depth: number,
): readonly PlanPoint[] {
  const halfWidth = width / 2;
  const halfDepth = depth / 2;
  return plan([
    [centerX - halfWidth, centerY - halfDepth],
    [centerX + halfWidth, centerY - halfDepth],
    [centerX + halfWidth, centerY + halfDepth],
    [centerX - halfWidth, centerY + halfDepth],
  ]);
}

function translatePlan(
  source: readonly PlanPoint[],
  centerX: number,
  centerY: number,
): readonly PlanPoint[] {
  return Object.freeze(
    source.map((point) =>
      Object.freeze({ x: point.x + centerX, y: point.y + centerY }),
    ),
  );
}

function chamferedRectangle(
  centerX: number,
  centerY: number,
  width: number,
  depth: number,
  chamfer: number,
): readonly PlanPoint[] {
  const left = centerX - width / 2;
  const right = centerX + width / 2;
  const rear = centerY - depth / 2;
  const front = centerY + depth / 2;
  return plan([
    [left + chamfer, rear],
    [right - chamfer, rear],
    [right, rear + chamfer],
    [right, front - chamfer],
    [right - chamfer, front],
    [left + chamfer, front],
    [left, front - chamfer],
    [left, rear + chamfer],
  ]);
}

function freezePrimitives(
  primitives: readonly GeometryPrimitive[],
): readonly GeometryPrimitive[] {
  return Object.freeze(primitives.map((primitive) => Object.freeze(primitive)));
}

